# Позиции, которые НЕ относятся к разлив (продается в стекле, шт).
BEER_EXCLUDED_NAMES = {
    "воронежское возрожденный рецепт 1978",
}


def normalize_beer_name(name: str) -> str:
    """Точечная замена написаний разливного пива согласно согласованным правилам.

    Возвращает "" для позиций-исключений (стекло), иначе — каноническое имя либо
    исходное название без изменений. Никаких подстрочных/регулярных матчей:
    только точное совпадение нормализованного имени (см. norm()).
    """
    if not name or not isinstance(name, str):
        return ""

    key = norm(name)

    for excl in BEER_EXCLUDED_NAMES:
        if excl in key:
            return ""

    return BEER_NAME_REPLACEMENTS.get(key, name.strip())